from pathlib import Path
import argparse
from render_profiles import catalog,canonical
ROOT=Path(__file__).resolve().parents[2]
TARGET=ROOT/'Packages/com.spatialwallpaper.sdk/Runtime/Security/RenderProfiles.Generated.cs'

def generate():
    value=canonical(catalog())
    return '// Generated by tools/sdk/generate_render_profiles.py; edit tools/sdk/render-profiles.json.\nnamespace SpatialWallpaper.Sdk.Security { internal static class RenderProfileSource { internal const string Json=@"'+value.replace('"','""')+'"; } }\n'

if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args();text=generate()
    if args.check:
        if not TARGET.exists() or TARGET.read_text(encoding='utf-8')!=text:raise SystemExit('generated render profile differs')
    else:TARGET.write_text(text,encoding='utf-8',newline='\n')
