def generate():
 data=json.loads(SOURCE.read_text(encoding='utf-8'))
 text=json.dumps(data,ensure_ascii=True,sort_keys=True,separators=(',',':'))
 digest=hashlib.sha256(text.encode()).hexdigest()
 metadata={**{key:data[key] for key in ['sdk','engine','pipeline','vm','backend']},'rules_sha256':digest,'policy_id':data['runtime_policy']['id']}
 # Unity builds embed the same identity in the actual SDK assembly. Standalone
 # trusted tools already receive their AssemblyMetadata from build_identity.
 attributes='#if UNITY_2022_3\n'+''.join('[assembly:System.Reflection.AssemblyMetadata('+json.dumps(key)+','+json.dumps(value)+')]\n' for key,value in metadata.items())+'#endif\n'
 return '// Generated by tools/sdk/generate_rules.py; edit tools/sdk/rules/v1.json.\n'+attributes+'namespace SpatialWallpaper.Sdk.Security { internal static class RuleSource { internal const string Digest="'+digest+'"; internal const string Json=@"'+text.replace('"','""')+'"; } }\n'
def policy():
 data=json.loads(SOURCE.read_text(encoding='utf-8'))['runtime_policy'];lines=['// Generated by tools/sdk/generate_rules.py; edit tools/sdk/rules/v1.json.','namespace SpatialWallpaper.Sdk.Hosting { public static class RuntimeLimits {']
 for key,value in data.items():
  name=''.join(part[:1].upper()+part[1:] for part in key.split('_'))
  if key=='id':lines.append(' public const string '+name+'='+json.dumps(value)+';')
  else:
   if type(value) is not int or not 0<value<=9223372036854775807:raise ValueError('invalid runtime policy number:'+key)
   wide=value>2147483647;lines.append(' public const '+('long' if wide else 'int')+' '+name+'='+str(value)+('L' if wide else '')+';')
 lines += [' public static void RequireRenderSize(int width,int height){if(width<1||height<1||width>MaxRenderSide||height>MaxRenderSide||(long)width*height>MaxRenderPixels)throw new System.PlatformNotSupportedException("render-size-not-validated-by-policy");}','}']
 all_rules=json.loads(SOURCE.read_text(encoding='utf-8'));names={item['capability'] for item in all_rules['members'] if item.get('capability')}
 for kinds in all_rules['content_capabilities'].values():
  for tags in kinds.values():names.update(tags)
 capabilities=sorted(names)
 digest=hashlib.sha256(json.dumps(all_rules,ensure_ascii=True,sort_keys=True,separators=(',',':')).encode()).hexdigest()
 lines += ['public static class CapabilityNames { public const string RulesDigest="'+digest+'";','public static bool Contains(string name){switch(name){']
 lines += ['case '+json.dumps(name)+':return true;' for name in capabilities]
 lines += ['default:return false;}}','} }']
 return '\n'.join(lines)+'\n'
