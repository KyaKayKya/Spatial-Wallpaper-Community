 members=[entry['id'] for entry in data['author_members']]
 if len(members)!=len(set(members)):raise ValueError('duplicate native author member')
 lines=['// Generated by tools/sdk/generate_rules.py; edit tools/sdk/rules/native-scene-v1.json.',
        'namespace SpatialWallpaper.Sdk.Native { public static class SceneCommandCatalog {',
        ' public const string Digest='+json.dumps(digest)+';',
        ' public const string TargetSdk='+json.dumps(data['sdk_target'])+';']
